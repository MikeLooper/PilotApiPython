from pydantic import ConfigDict, Field

from pilot_api.dto.schemas.base import DtoBase


class ProblemDetailsDto(DtoBase):
    # RFC 9457 allows extension members, so unlike other DTOs extras are permitted.
    model_config = ConfigDict(populate_by_name=True, extra="allow")

    type: str | None = Field(
        description="A URI reference that identifies the problem type. Typically links to "
        "documentation.",
        examples=["/errors/AccountNumberNotFound"],
    )
    title: str | None = Field(
        description="A short, human-readable summary of the problem type. It should not change "
        "between occurrences of the same error.",
        examples=["Insufficient Funds"],
    )
    status: int | None = Field(
        default=None,
        description="The HTTP status code generated by the origin server for this occurrence of "
        "the problem.",
        examples=[500],
    )
    detail: str | None = Field(
        default=None,
        description="A human-readable explanation specific to this occurrence of the problem.",
        examples=["Your current balance is $15.00, but the item costs $20.00."],
    )
    instance: str | None = Field(
        default=None,
        description="A URI reference that identifies the specific occurrence of the problem "
        "(often the request path).",
        examples=["/api/checkout/session_9281a"],
    )
